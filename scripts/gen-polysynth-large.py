#!/usr/bin/env python3
"""Writes examples/patches/polysynth-large.ron, the second reference patch of
NFR-PERF-01 (docs/design/polyphony.md, The large reference patch).

Run it from the repository root:

    python3 scripts/gen-polysynth-large.py

To change the patch, edit this script and run it again, rather than edit the
RON file by hand. Plain Python 3, with no dependencies.

Each chain is one row, left to right in signal order, and module IDs follow
that order, so Tab and a screen reader meet each chain from its source to its
end.
"""

from pathlib import Path

# Grid spacing on the canvas, in canvas units.
COLUMN = 320.0
ROW = 480.0

HEADER = """\
// Layered polysynth (benchmark): the second reference patch of NFR-PERF-01
// (docs/design/polyphony.md, The large reference patch). The first, the
// polysynth, is a minimal instrument. This one is a full one: four sound
// layers and a noise layer on each of 8 voices, then a stereo effect chain.
// Its cost is measured against the budget of 25% of one core.
//
// This file is generated by scripts/gen-polysynth-large.py. To change it,
// edit the script and run `python3 scripts/gen-polysynth-large.py` from the
// repository root, rather than edit this file by hand.
//
// How it is laid out. Each chain is one row, left to right in the order the
// signal flows, and module IDs follow that order:
// - Row 1: MIDI Note (1) and Voice Assigner (2), both at 8 voices, and an
//   Add that puts the shared vibrato on each voice's pitch.
// - Rows 2 to 5: the four layers, saw, pulse, triangle, and sine. Each has
//   its own detune (Voice Spread), phase, oscillator, a slow LFO with a slew
//   and a depth, a filter with its own envelope, and an amplitude envelope
//   and Amplifier.
// - Row 6: the voice's tail: a mixer of the four layers, the noise layer
//   added in, a drive and clip stage, a final ladder filter, and an output
//   Amplifier that follows velocity.
// - Row 7: the noise source and its band-pass filter, shared by every voice.
// - Row 8: Voice Merge, then the stereo effects: two echoes, one per side,
//   joined into stereo, six all-pass stages for diffusion, EQ, dynamics,
//   a wet and dry mix, the master Amplifier, and Audio Out.
// - Row 9: shared modulation: two slow LFOs that move the echo times, the
//   Brightness and Drive macros, a vibrato LFO with its depth macro, and the
//   patch Transport.
// Every module from the Voice Assigner to Voice Merge runs once per voice.
// Hover over an output in a layer to see "8 voices".
//
// MIDI Note into a Voice Assigner is here so the benchmark measures the
// assigner. It is not a pattern to copy: MIDI Note already gives each note
// its own voice.
//
// To play it, use a MIDI keyboard. With no hardware on macOS or Linux, run
// `loom midi-port "Loom Pad"` in a terminal, before or after starting the
// app, then type `on 60`, `on 64`, and `on 67`. On Windows, use a MIDI
// keyboard.
//
// What to turn:
// - Brightness (macro) opens the final filter of every voice.
// - Drive (macro) pushes each voice into its clip stage.
// - Vibrato (macro) sets the depth of the 5 Hz vibrato.
// - Each layer's filter cutoff and the Mixer's four levels set the blend.
// - The wet and dry Crossfade sets how much of the diffusion you hear.
//
// The benchmark holds 8 notes, two four-note chords: C, E, G, B from middle
// C, and the same an octave down. The master Amplifier's gain, 0.3, keeps
// them under -1 dBFS: they measure about 0.48 (-6 dBFS), and a test checks
// it with output safety off. One note plays near -16 dBFS. Run the benchmark
// with
// `cargo bench -p loom-modules --bench engine -- polysynth-large`.
"""


class Patch:
    """Collects modules and cables, numbering modules in the order they are
    added, which is signal order."""

    def __init__(self):
        self.modules = []
        self.cables = []

    def add(self, row, column, kind, params=None, ranges=None, comment=None):
        """Adds a module on `row` at `column` and returns its ID."""
        module_id = len(self.modules) + 1
        self.modules.append((module_id, kind, row, column, params or {}, ranges or {}, comment))
        return module_id

    def cable(self, source, output, target, port):
        """Connects `output` of `source` to input `port` of `target`."""
        self.cables.append((source, output, target, port))

    def ron(self):
        """The patch as RON text."""
        lines = [HEADER.rstrip("\n"), "Patch(", "    version: 1,", "    metadata: Metadata(",
                 '        name: "Layered polysynth (benchmark)",', '        license: "CC0-1.0",', "    ),",
                 "    modules: ["]
        for module_id, kind, row, column, params, ranges, comment in self.modules:
            if comment:
                lines.append(f"        // {comment}")
            fields = [f"id: {module_id}", f'kind: "{kind}@1"']
            if params:
                fields.append("params: {" + ", ".join(f'"{k}": {number(v)}' for k, v in params.items()) + "}")
            if ranges:
                fields.append(
                    "ranges: {" + ", ".join(f'"{k}": ({number(a)}, {number(b)})' for k, (a, b) in ranges.items()) + "}"
                )
            fields.append(f"position: Some(({number(column * COLUMN)}, {number(row * ROW)}))")
            lines.append("        PatchModule(" + ", ".join(fields) + "),")
        lines += ["    ],", "    cables: ["]
        for source, output, target, port in self.cables:
            lines.append(f'        PatchCable(from: ({source}, "{output}"), to: ({target}, "{port}")),')
        lines += ["    ],", ")"]
        return "\n".join(lines) + "\n"


def number(value):
    """A RON float, always with a decimal point."""
    text = repr(float(value))
    return text


# The four layers: oscillator, octave of its phase, detune amount and seed,
# the LFO's pitch offset (key-tracked, about -9 octaves), the filter, its
# output and settings, the filter envelope, and the amplitude envelope.
LAYERS = [
    {
        "osc": "loom.osc.saw", "octave": 0.0, "detune": 0.0003, "seed": 1.0, "lfo": -0.9,
        "filter": "loom.filter.svf", "filter_out": "lowpass", "filter_params": {"cutoff": 900.0, "resonance": 0.3},
        "filter_env": {"attack": 0.005, "decay": 0.4, "sustain": 0.3, "release": 0.8},
        "amp_env": {"attack": 0.01, "decay": 0.5, "sustain": 0.7, "release": 0.8},
    },
    {
        "osc": "loom.osc.pulse", "octave": -1.0, "detune": 0.0004, "seed": 2.0, "lfo": -0.88,
        "osc_params": {"width": 0.35},
        "filter": "loom.filter.ladder", "filter_out": "out", "filter_params": {"cutoff": 700.0, "resonance": 0.3},
        "filter_env": {"attack": 0.005, "decay": 0.6, "sustain": 0.3, "release": 0.8},
        "amp_env": {"attack": 0.02, "decay": 0.5, "sustain": 0.6, "release": 0.6},
    },
    {
        "osc": "loom.osc.triangle", "octave": 1.0, "detune": 0.0002, "seed": 3.0, "lfo": -0.92,
        "filter": "loom.filter.onepole", "filter_out": "lowpass", "filter_params": {"cutoff": 2000.0},
        "filter_env": {"attack": 0.005, "decay": 0.8, "sustain": 0.3, "release": 0.8},
        "amp_env": {"attack": 0.3, "decay": 0.5, "sustain": 0.8, "release": 1.5},
    },
    {
        "osc": "loom.osc.sine", "octave": 0.0, "detune": 0.0005, "seed": 4.0, "lfo": -0.86,
        "filter": "loom.filter.svf", "filter_out": "lowpass", "filter_params": {"cutoff": 1500.0, "resonance": 0.2},
        "filter_env": {"attack": 0.005, "decay": 0.5, "sustain": 0.3, "release": 0.8},
        "amp_env": {"attack": 0.5, "decay": 0.5, "sustain": 0.8, "release": 2.0},
    },
]

# The Mixer's level for each layer, as a gain (the Mixer shows it in dB).
LAYER_LEVELS = [0.5, 0.35, 0.35, 0.25]

# The master Amplifier's gain, set by measurement so the benchmark's 8 notes
# peak under -1 dBFS (tests/polyphony.rs checks it).
MASTER_GAIN = 0.3


def build():
    """The layered polysynth, in signal order."""
    p = Patch()
    note = p.add(0, 0, "loom.midi.note", {"voices": 8.0, "mode": 0.0}, comment="8 voices, Oldest mode.")
    assign = p.add(0, 1, "loom.voice.assign", {"voices": 8.0, "mode": 0.0, "unison": 1.0},
                   comment="8 voices, Oldest mode: measured here, not a pattern to copy.")
    for port in ["pitch", "gate", "velocity", "pressure", "timbre"]:
        p.cable(note, port, assign, port)
    vibrato_pitch = p.add(0, 2, "loom.math.add", comment="Each voice's pitch with the shared vibrato.")
    p.cable(assign, "pitch", vibrato_pitch, "a")

    layer_amps = []
    layer_amp_envs = []
    for index, layer in enumerate(LAYERS):
        row = index + 1
        spread = p.add(row, 0, "loom.voice.spread", {"amount": layer["detune"], "mode": 2.0, "seed": layer["seed"]},
                       {"amount": (-0.01, 0.01)}, comment=f"Layer {index + 1}: {layer['osc'].split('.')[-1]}.")
        phase = p.add(row, 1, "loom.phase.generator", {"octave": layer["octave"]})
        osc = p.add(row, 2, layer["osc"], layer.get("osc_params"))
        lfo_pitch = p.add(row, 3, "loom.math.add", {"offset": layer["lfo"]}, {"offset": (-1.0, 1.0)})
        lfo_phase = p.add(row, 4, "loom.phase.generator")
        lfo = p.add(row, 5, "loom.mod.lfo")
        slew = p.add(row, 6, "loom.level.slew", {"rise": 0.1, "fall": 0.1})
        lfo_depth = p.add(row, 7, "loom.math.mul", {"gain": 0.03})
        filter_env = p.add(row, 8, "loom.env.envelope", layer["filter_env"])
        env_depth = p.add(row, 9, "loom.math.mul", {"gain": 0.2})
        cutoff = p.add(row, 10, "loom.math.add")
        filt = p.add(row, 11, layer["filter"], layer["filter_params"])
        amp_env = p.add(row, 12, "loom.env.envelope", layer["amp_env"])
        amp = p.add(row, 13, "loom.level.amp")
        p.cable(vibrato_pitch, "out", spread, "in")
        p.cable(spread, "out", phase, "pitch")
        p.cable(phase, "phase", osc, "phase")
        p.cable(assign, "pitch", lfo_pitch, "a")
        p.cable(lfo_pitch, "out", lfo_phase, "pitch")
        p.cable(lfo_phase, "phase", lfo, "phase")
        p.cable(lfo, "out", slew, "in")
        p.cable(slew, "out", lfo_depth, "a")
        p.cable(assign, "gate", filter_env, "gate")
        p.cable(filter_env, "out", env_depth, "a")
        p.cable(lfo_depth, "out", cutoff, "a")
        p.cable(env_depth, "out", cutoff, "b")
        p.cable(osc, "out", filt, "in")
        p.cable(cutoff, "out", filt, "cutoff")
        p.cable(assign, "gate", amp_env, "gate")
        p.cable(filt, layer["filter_out"], amp, "in")
        p.cable(amp_env, "out", amp, "level")
        layer_amps.append(amp)
        layer_amp_envs.append(amp_env)

    tail = 5
    mixer = p.add(tail, 0, "loom.mix.mixer", {f"level{i + 1}": level for i, level in enumerate(LAYER_LEVELS)},
                  comment="The voice's tail.")
    noise_amp = p.add(tail, 1, "loom.level.amp", {"gain": 0.05})
    with_noise = p.add(tail, 2, "loom.math.add")
    drive = p.add(tail, 3, "loom.math.mul")
    clip = p.add(tail, 4, "loom.level.clamp", {"low": -0.6, "high": 0.6})
    final_filter = p.add(tail, 5, "loom.filter.ladder", {"cutoff": 2500.0, "resonance": 0.25, "drive": 0.2})
    out_amp = p.add(tail, 6, "loom.level.amp")
    for i, amp in enumerate(layer_amps):
        p.cable(amp, "out", mixer, f"in{i + 1}")
    p.cable(layer_amp_envs[0], "out", noise_amp, "level")
    p.cable(mixer, "out", with_noise, "a")
    p.cable(noise_amp, "out", with_noise, "b")
    p.cable(with_noise, "out", drive, "a")
    p.cable(drive, "out", clip, "in")
    p.cable(clip, "out", final_filter, "in")
    p.cable(final_filter, "out", out_amp, "in")
    p.cable(assign, "velocity", out_amp, "level")

    noise = p.add(6, 0, "loom.osc.noise", comment="Noise, shared by every voice.")
    noise_filter = p.add(6, 1, "loom.filter.svf", {"cutoff": 3000.0, "resonance": 0.5})
    p.cable(noise, "out", noise_filter, "in")
    p.cable(noise_filter, "bandpass", noise_amp, "in")

    fx = 7
    merge = p.add(fx, 0, "loom.voice.merge", comment="Voice Merge (Sum), then the stereo effects.")
    echo_left = p.add(fx, 1, "loom.time.delay", {"time": 0.3})
    mix_left = p.add(fx, 2, "loom.mix.crossfade", {"mix": 0.25})
    echo_right = p.add(fx, 3, "loom.time.delay", {"time": 0.45})
    mix_right = p.add(fx, 4, "loom.mix.crossfade", {"mix": 0.25})
    join = p.add(fx, 5, "loom.mix.join")
    diffusion = [p.add(fx, 6 + i, "loom.time.allpass", {"time": t, "gain": 0.5})
                 for i, t in enumerate([0.0047, 0.0061, 0.0083, 0.0109, 0.0137, 0.0171])]
    eq = p.add(fx, 12, "loom.eq.eq", {"low_cut": 60.0, "high_gain": -2.0})
    dynamics = p.add(fx, 13, "loom.dyn.dynamics", {"threshold": -12.0, "ratio": 3.0})
    wet_dry = p.add(fx, 14, "loom.mix.crossfade", {"mix": 0.5})
    master = p.add(fx, 15, "loom.level.amp", {"gain": MASTER_GAIN},
                   comment="The master gain keeps 8 held notes under -1 dBFS.")
    out = p.add(fx, 16, "loom.io.audio-out")
    p.cable(out_amp, "out", merge, "in")
    p.cable(merge, "out", echo_left, "in")
    p.cable(merge, "out", mix_left, "a")
    p.cable(echo_left, "out", mix_left, "b")
    p.cable(merge, "out", echo_right, "in")
    p.cable(merge, "out", mix_right, "a")
    p.cable(echo_right, "out", mix_right, "b")
    p.cable(mix_left, "out", join, "left")
    p.cable(mix_right, "out", join, "right")
    previous = (join, "out")
    for stage in diffusion:
        p.cable(previous[0], previous[1], stage, "in")
        previous = (stage, "out")
    p.cable(previous[0], previous[1], eq, "in")
    p.cable(eq, "out", dynamics, "in")
    p.cable(join, "out", wet_dry, "a")
    p.cable(dynamics, "out", wet_dry, "b")
    p.cable(wet_dry, "out", master, "in")
    p.cable(master, "out", out, "in")

    mod = 8
    drift_left = p.add(mod, 0, "loom.mod.lfo", {"rate": 0.13}, comment="Shared modulation.")
    drift_left_depth = p.add(mod, 1, "loom.math.mul", {"gain": 0.002})
    drift_right = p.add(mod, 2, "loom.mod.lfo", {"rate": 0.17})
    drift_right_depth = p.add(mod, 3, "loom.math.mul", {"gain": 0.002})
    brightness = p.add(mod, 4, "loom.ui.macro", {"value": 0.5}, comment="Brightness.")
    brightness_depth = p.add(mod, 5, "loom.math.mul", {"gain": 0.1})
    drive_macro = p.add(mod, 6, "loom.ui.macro", {"value": 0.8}, comment="Drive.")
    vibrato = p.add(mod, 7, "loom.mod.lfo", {"rate": 5.0}, comment="Vibrato: 5 Hz, its depth set by the macro.")
    vibrato_macro = p.add(mod, 8, "loom.ui.macro", {"value": 0.3})
    vibrato_depth = p.add(mod, 9, "loom.math.mul", {"gain": 0.002})
    p.add(mod, 10, "loom.clock.transport", comment="The patch transport: 120 BPM, 4/4, running.")
    p.cable(vibrato, "out", vibrato_depth, "a")
    p.cable(vibrato_macro, "out", vibrato_depth, "b")
    p.cable(vibrato_depth, "out", vibrato_pitch, "b")
    p.cable(drift_left, "out", drift_left_depth, "a")
    p.cable(drift_left_depth, "out", echo_left, "time")
    p.cable(drift_right, "out", drift_right_depth, "a")
    p.cable(drift_right_depth, "out", echo_right, "time")
    p.cable(brightness, "out", brightness_depth, "a")
    p.cable(brightness_depth, "out", final_filter, "cutoff")
    p.cable(drive_macro, "out", drive, "b")
    return p


def main():
    root = Path(__file__).resolve().parent.parent
    path = root / "examples" / "patches" / "polysynth-large.ron"
    path.write_text(build().ron())
    print(f"wrote {path.relative_to(root)}")


if __name__ == "__main__":
    main()
